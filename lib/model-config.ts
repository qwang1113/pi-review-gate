/**
 * pi-review-gate — per-agent model-chain configuration layer (agents section).
 *
 * WHY: the agent models used to be edited by hand in each `agents/*.md`
 * frontmatter. This module adds a config layer (`agents` section of
 * `.pi/review-gate.json` / `~/.pi/review-gate.json`, layered like precommit):
 *
 *   {
 *     "agents": {
 *       "reviewer": { "auto": false, "slots": ["onekey/gpt-5.6-sol:high", "claude-fable-5:max", "onekey/glm-5.3:high"] },
 *       "worker":   { "auto": false, "slots": ["opencode-go/deepseek-v4-flash:high"] }
 *     }
 *   }
 *
 * Semantics per configured agent:
 *   - NOT configured in this layer  → the renderer cleans up any generated
 *     copy this layer used to hold (back to the upstream default).
 *   - `auto: false` + slots          → `slots[0]` becomes the main model,
 *     `slots[1..]` the fallback chain, each entry keeping its own
 *     `:thinking` suffix (pi-subagents supports per-model thinking levels).
 *   - `auto: true` (explicit)        → the renderer writes a *default-chain
 *     overlay* (generated marker + the upstream default model chain). This
 *     lets a higher-precedence layer SHADOW a lower layer's slot render: with
 *     global `reviewer.auto:false` + slots, a project `reviewer.auto:true`
 *     must deploy the built-in default — not leave the global slots render in
 *     force (the deployed model would then contradict the effective config).
 *
 * Two layers, each rendered into its OWN agent directory (pi-subagents loads
 * both, project overriding user-global):
 *   - project layer → <project>/.pi/agents/*.md
 *   - global  layer → ~/.pi/agent/agents/*.md
 *
 * The extension and the installer call `applyAgentConfigLayer`;
 * `install-package.mjs` applies ONLY the global layer after copying (its
 * cwd is not trustworthy).
 *
 * Fail-safe: a missing/corrupt section, an unresolvable spec or an
 * incompatible thinking level NEVER loosens the gate — validation fails the
 * write and keeps the previous file.
 */

import { copyFileSync, existsSync, mkdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** Max slots an agent may configure; longer lists are truncated with a diagnostic. */
export const MAX_SLOTS = 4;

/** Marker line placed at the top of a generated frontmatter so render products
 *  can be recognized and only generated files are ever deleted/restored.
 *  Sits on a line that does not match a `key:` pattern, so pi-subagents'
 *  frontmatter parser ignores it. */
export const GENERATED_MARKER = "# @generated by pi-review-gate models";

/** The 12 agent files the package ships. */
export const KNOWN_AGENTS: readonly string[] = Object.freeze([
  "reviewer",
  "reviewer-readonly",
  "module-reviewer",
  "adviser",
  "arbiter",
  "worker",
  "worker-readonly",
  "fixer",
  "planner",
  "triage",
  "recon",
  "goal-auditor",
]);

/**
 * Locate the `agents/` directory INSIDE this package.
 *
 * We PROBE the layouts the package really ships under instead of trusting one
 * relative path — the same lesson `resolveTrustedRunner` (extensions/
 * review-gate.ts) had to learn: `<here>/../agents` resolves in the dev repo
 * but not in every install layout, and a self-heal riding an unresolvable
 * path fails SILENTLY, which is precisely how a bootstrap deadlock survives.
 *
 * Evaluated lazily at CALL time, never at module scope, and defensive about
 * `import.meta.url`: scripts/install-package.mjs imports this module as a
 * base64 DATA URL, where `fileURLToPath` throws. A module-level evaluation
 * would take the whole postinstall render down with it; null lets each caller
 * fall back to the sourceDir it already knows.
 *
 * `baseDir` exists so the PROBE ORDER itself is testable against temp dirs
 * (production callers pass nothing and get this module's own directory); it is
 * never a runtime override.
 */
export function resolvePackageAgentsDir(baseDir?: string): string | null {
  let here: string;
  if (baseDir !== undefined) here = baseDir;
  else {
    try { here = dirname(fileURLToPath(import.meta.url)); } catch { return null; }
  }
  const candidates = [
    join(here, "agents"),             // package root layout
    join(here, "..", "agents"),       // lib/ sibling (repo + published package)
    join(here, "..", "..", "agents"), // nested install layout
  ];
  for (const c of candidates) {
    // IDENTITY, not just existence: the third candidate reaches two levels up,
    // where an unrelated `agents/` directory can easily live (a monorepo
    // sibling, a user's own folder). Adopting one would feed foreign files to
    // BOTH the chain renderer and the self-heal copy, so a candidate only
    // counts when it actually holds this package's roles.
    try {
      if (existsSync(c) && statSync(c).isDirectory() && existsSync(join(c, "reviewer.md"))) return c;
    } catch { /* keep probing */ }
  }
  return null;
}

export interface EnsureAgentFilesResult {
  /** Agent names whose missing file was restored by this call. */
  copied: string[];
  /** Human-readable problems (never thrown — a session must not die on this). */
  problems: string[];
}

/**
 * Bootstrap self-heal: restore any KNOWN_AGENTS file that is MISSING from the
 * user's agents dir.
 *
 * Without it a newly shipped role only appears after the postinstall runs
 * again, and a role the gate REQUIRES (goal-auditor) would be undispatchable
 * until then — no audit, no goal approval, and in loop mode not even an edit:
 * a deadlock whose only exit is turning the gate off. Healing at session start
 * kills that class for every future role.
 *
 * Deliberately narrow: it only fills GAPS. An existing file (hand-written,
 * rendered, or user-edited) is never touched, so this cannot clobber a
 * configured chain — it just re-establishes the same ownership AGENTS.md
 * already declares for the installed copies.
 */
export function ensureAgentFilesPresent(opts: {
  sourceDir: string | null;
  targetDir: string;
  agents: readonly string[];
}): EnsureAgentFilesResult {
  const copied: string[] = [];
  const problems: string[] = [];
  if (!opts.sourceDir) {
    problems.push(
      "cannot locate the package agents directory (包内 agents 目录无法定位) — missing agent roles " +
      "cannot self-heal; reinstall the package to restore them",
    );
    return { copied, problems };
  }
  for (const name of opts.agents) {
    const target = join(opts.targetDir, `${name}.md`);
    const source = join(opts.sourceDir, `${name}.md`);
    try {
      if (existsSync(target)) continue; // idempotent: gaps only, never an overwrite
      if (!existsSync(source)) continue; // nothing to heal from
      mkdirSync(opts.targetDir, { recursive: true });
      copyFileSync(source, target);
      copied.push(name);
    } catch (e) {
      problems.push(`${name}: could not restore the missing agent file (${e instanceof Error ? e.message : String(e)})`);
    }
  }
  return { copied, problems };
}

// ---------------------------------------------------------------------------
// Model spec parsing: `provider/id:thinking` | `id:thinking` | `provider/id` | `id`
// ---------------------------------------------------------------------------

export interface ModelSpec {
  provider: string | null;
  id: string;
  thinking: string | null;
  raw: string;
}

/**
 * The thinking levels pi understands. Single source in lib/: shared by
 * splitThinkingSuffix / parseModelSpec here and bareModelId / specThinking in
 * lib/review-fanout.ts — an ollama-style letter tag (`qwen3:latest`) is NOT a
 * level and is never stripped or carried (round-6 P2: two diverging copies
 * made the fan-out and the renderer disagree about such ids).
 * Mirrors pi-subagents' level list.
 */
export const KNOWN_THINKING_LEVELS: ReadonlySet<string> = new Set(["off", "low", "medium", "high", "xhigh", "max", "minimal"]);

/**
 * Split a trailing `:level` off a spec — the level is a KNOWN thinking level
 * (off/low/…/max), never part of an id.
 */
export function splitThinkingSuffix(spec: string): { base: string; thinking: string | null } {
  const colonIdx = spec.lastIndexOf(":");
  if (colonIdx === -1) return { base: spec, thinking: null };
  const suffix = spec.slice(colonIdx + 1);
  if (!KNOWN_THINKING_LEVELS.has(suffix)) return { base: spec, thinking: null };
  return { base: spec.slice(0, colonIdx), thinking: suffix };
}

export function parseModelSpec(spec: string): ModelSpec {
  const raw = spec.trim();
  if (!raw) return { provider: null, id: "", thinking: null, raw };
  // CR/LF inside a spec is never legitimate — it would inject extra
  // frontmatter lines when the spec is rendered into an agent file
  // (round-11 P1: `p/m\ntools: bash`). Refuse at the parse boundary.
  if (/[\r\n]/.test(raw)) return { provider: null, id: "", thinking: null, raw };
  const { base, thinking } = splitThinkingSuffix(raw);
  // A LEADING slash (slash === 0) is malformed, not a provider split: it
  // must not silently drop the slash and pass as a provider-less id (that
  // accepted "/gpt-5.6-sol" wherever "gpt-5.6-sol" resolved). Keeping the
  // whole base as the id makes the registry lookup fail → validateSpec
  // refuses the write (fail-safe).
  const slash = base.indexOf("/");
  if (slash <= 0) return { provider: null, id: base.trim(), thinking, raw };
  return { provider: base.slice(0, slash).trim(), id: base.slice(slash + 1).trim(), thinking, raw };
}

/** Bare model id (no provider, no thinking). */
export function bareModelId(spec: string): string {
  return parseModelSpec(spec).id;
}

export function formatSpec(provider: string | null, id: string, thinking: string | null): string {
  const base = provider ? `${provider}/${id}` : id;
  return thinking ? `${base}:${thinking}` : base;
}

// ---------------------------------------------------------------------------
// Registry: what the launch layer can actually resolve.
// ---------------------------------------------------------------------------

export interface RegistryModelInfo {
  id: string;
  /** `false` means the provider exposes only the `off` thinking level. */
  reasoning?: boolean;
  /** thinking level → mapped level (null when the level is unsupported). */
  thinkingLevelMap: Record<string, string | null> | null | undefined;
}

export type ModelRegistry = Record<string, RegistryModelInfo[]>;

function readJsonIfExists(path: string): unknown {
  try {
    return existsSync(path) ? JSON.parse(readFileSync(path, "utf8")) : undefined;
  } catch {
    return undefined; // corrupt — registry degrades gracefully
  }
}

/** Merge models.json (hand-written) and models-store.json (provider cache). */
export function loadRegistry(home = homedir()): ModelRegistry {
  const registry: ModelRegistry = {};
  const ingest = (root: unknown) => {
    if (typeof root !== "object" || root === null) return;
    const providers = (root as Record<string, unknown>).providers ?? root;
    for (const [provider, value] of Object.entries(providers as Record<string, unknown>)) {
      if (typeof value !== "object" || value === null) continue;
      const models = (value as Record<string, unknown>).models;
      if (!Array.isArray(models)) continue;
      const list = (registry[provider] ??= []);
      for (const m of models) {
        if (typeof m !== "object" || m === null) continue;
        const entry = m as Record<string, unknown>;
        const id = entry.id;
        if (typeof id !== "string" || !id) continue;
        const tlm = entry.thinkingLevelMap;
        const thinkingLevelMap =
          typeof tlm === "object" && tlm !== null && !Array.isArray(tlm)
            ? Object.fromEntries(
                Object.entries(tlm).filter(([, mapped]) => mapped === null || typeof mapped === "string"),
              ) as Record<string, string | null>
            : undefined;
        const reasoning = typeof entry.reasoning === "boolean" ? entry.reasoning : undefined;
        const existing = list.find((e) => e.id === id);
        if (existing) {
          // The FIRST source still wins the entry, but a later one may carry
          // metadata the first one lacked. Dropping it outright made a
          // metadata-less models.json entry SHADOW the store's map, and "no
          // map" means `:max` is refused — so the renderer rejected a level
          // the registry actually proves supported. Fill gaps only; never
          // overwrite what the higher-priority source already stated.
          if (existing.thinkingLevelMap === undefined && thinkingLevelMap !== undefined) {
            existing.thinkingLevelMap = thinkingLevelMap;
          }
          if (existing.reasoning === undefined && reasoning !== undefined) {
            existing.reasoning = reasoning;
          }
          continue;
        }
        list.push({ id, reasoning, thinkingLevelMap });
      }
    }
  };
  ingest(readJsonIfExists(join(home, ".pi", "agent", "models.json")));
  ingest(readJsonIfExists(join(home, ".pi", "agent", "models-store.json")));
  return registry;
}

/**
 * All `provider/id:level` entries the registry proves supported for `spec`.
 * Missing metadata follows pi-subagents' defaults: every level except `max`
 * is allowed, while mapped null and unlisted `xhigh`/`max` are refused.
 */
export function supportedThinkingOptions(reg: ModelRegistry, spec: string): string[] {
  const { provider, id } = parseModelSpec(spec);
  const cands: Array<{ provider: string; info: RegistryModelInfo }> = [];
  if (provider) {
    for (const info of reg[provider] ?? []) if (info.id === id) cands.push({ provider, info });
  } else {
    for (const [p, models] of Object.entries(reg))
      for (const info of models) if (info.id === id) cands.push({ provider: p, info });
  }
  if (cands.length === 0) return [];
  const out = new Set<string>();
  for (const c of cands) {
    const tlm = c.info.thinkingLevelMap;
    if (c.info.reasoning === false) {
      out.add(`${c.provider}/${c.info.id}:off`);
      continue;
    }
    for (const level of KNOWN_THINKING_LEVELS) {
      const mapped = tlm?.[level];
      if (mapped === null || (mapped === undefined && level === "max")) continue;
      if (mapped === undefined && level === "xhigh" && tlm) continue;
      out.add(`${c.provider}/${c.info.id}:${level}`);
    }
  }
  return [...out].sort();
}

// ---------------------------------------------------------------------------
// Validation
// ---------------------------------------------------------------------------

export interface SpecValidation {
  ok: boolean;
  /** Hard failure reason (write is refused). */
  reason?: string;
  /** Soft warning (write proceeds). */
  warning?: string;
}

/**
 * Validate one slot spec against the registry and launch allowlist.
 * Ambiguous provider-less ids and reasoning:false models are rejected for
 * unsupported thinking levels; opencode-go remains restricted to flash.
 */
export function validateSpec(reg: ModelRegistry, spec: string): SpecValidation {
  const parsed = parseModelSpec(spec);
  if (!parsed.id) return { ok: false, reason: `empty spec: "${spec}"` };

  const candidates: Array<{ provider: string; info: RegistryModelInfo }> = [];
  if (parsed.provider) {
    if (!reg[parsed.provider]) return { ok: false, reason: `provider not in the registry: "${parsed.provider}" (spec "${spec}")` };
    for (const info of reg[parsed.provider]) if (info.id === parsed.id) candidates.push({ provider: parsed.provider, info });
  } else {
    for (const [provider, models] of Object.entries(reg))
      for (const info of models) if (info.id === parsed.id) candidates.push({ provider, info });
    if (new Set(candidates.map((c) => c.provider)).size > 1) {
      return { ok: false, reason: `ambiguous model spec: "${spec}" exists under several providers — write it as provider/id` };
    }
  }
  if (candidates.length === 0) return { ok: false, reason: `model cannot be resolved: "${spec}" (absent from the registry)` };

  if (parsed.provider === "opencode-go" && parsed.id !== "deepseek-v4-flash") {
    return { ok: false, reason: `opencode-go only allows deepseek-v4-flash (cost allowlist), got "${spec}"` };
  }
  if (!parsed.provider && candidates.every((c) => c.provider === "opencode-go") && parsed.id !== "deepseek-v4-flash") {
    return { ok: false, reason: `opencode-go only allows deepseek-v4-flash, got "${spec}"` };
  }

  if (parsed.thinking) {
    const level = parsed.thinking;
    const supports = (info: RegistryModelInfo): boolean => {
      if (info.reasoning === false) return level === "off";
      const map = info.thinkingLevelMap;
      if (!map) return level !== "max";
      const mapped = map[level];
      if (mapped === null) return false;
      if ((level === "xhigh" || level === "max") && mapped === undefined) return false;
      return true;
    };
    if (!candidates.some(({ info }) => supports(info))) {
      const mapped = candidates
        .flatMap(({ info }) => Object.entries(info.thinkingLevelMap ?? {}))
        .filter(([, m]) => m !== null && m !== undefined)
        .map(([name]) => name)
        .sort();
      // A reasoning:false model DOES support one level — `off` — and nothing
      // else, but it carries no thinkingLevelMap, so the generic branch said
      // "supported: no metadata" and left the user with no idea what to pin.
      const allNonReasoning = candidates.every(({ info }) => info.reasoning === false);
      const supported = mapped.length > 0 ? mapped.join("/") : allNonReasoning ? "off" : "no metadata";
      return {
        ok: false,
        reason: `model ${parsed.provider ? parsed.provider + "/" : ""}${parsed.id} does not support thinking level "${level}" (supported: ${supported})`,
      };
    }
    if (candidates.every(({ info }) => !info.thinkingLevelMap && info.reasoning !== false)) {
      return { ok: true, warning: `model ${parsed.id} has no thinking-level metadata; level "${level}" is unverified (allowed)` };
    }
    return { ok: true };
  }
  return { ok: true };
}

/** Validate a whole slot list; first failure wins. */
export function validateSlots(reg: ModelRegistry, slots: readonly string[]): SpecValidation {
  for (const s of slots) {
    const v = validateSpec(reg, s);
    if (!v.ok) return v;
  }
  return { ok: true };
}

